#!/usr/bin/env node
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));

const readText = (relativePath) => readFileSync(join(repoRoot, relativePath), "utf8");
const normalizeWhitespace = (text) => text.replace(/\s+/g, " ");

const changelog = readText("CHANGELOG.md");
const changelogDoc = readText("docs/changelog-metadata.md");
const releaseDoc = normalizeWhitespace(readText("docs/release.md"));
const qualityDoc = normalizeWhitespace(readText("docs/quality-gates.md"));
const siteDoc = normalizeWhitespace(readText("docs/site.md"));
const packageJson = JSON.parse(readText("package.json"));
const scripts = packageJson.scripts ?? {};

const failures = [];

const requireIncludes = (name, text, fragments) => {
  for (const fragment of fragments) {
    if (!text.includes(fragment)) {
      failures.push(`${name} is missing: ${fragment}`);
    }
  }
};

const requireExcludes = (name, text, fragments) => {
  for (const fragment of fragments) {
    if (text.includes(fragment)) {
      failures.push(`${name} must not include: ${fragment}`);
    }
  }
};

if (scripts["verify:changelog"] !== "node scripts/changelog-metadata-verify.mjs") {
  failures.push("package.json verify:changelog script is missing or mismatched");
}

if (!scripts["verify:release"]?.includes("npm run verify:changelog")) {
  failures.push("package.json verify:release must include npm run verify:changelog");
}

requireIncludes("CHANGELOG.md", changelog, [
  "# Changelog",
  "Keep a Changelog",
  "Conventional Commits",
  "## [Unreleased]",
  "### Added",
  "### Changed",
  "### Fixed",
  "The changelog metadata gate validates ownership and structure only.",
  "does not",
  "generate release notes",
]);

requireExcludes("CHANGELOG.md", changelog, [
  "github.com/yuxuetr/rust-template",
  "yuxuetr/rust-template",
  "rust-template",
  "generated by git-cliff",
]);

requireIncludes("docs/changelog-metadata.md", changelogDoc, [
  "Project-owned changelog structure",
  "Unreleased section",
  "Keep a Changelog",
  "Conventional Commits",
  "stale template-link bans",
  "github.com/yuxuetr/rust-template",
]);

requireIncludes("docs/release.md", releaseDoc, [
  "Changelog metadata checks are read-only",
  "project-owned changelog structure, Unreleased section, Keep a Changelog and Conventional Commits references, and stale template-link bans",
  "they do not generate release notes, run git-cliff, derive changes from Git history, create tags, publish releases, or rewrite commit history",
  "Before `1.0`, API changes are allowed but should still be documented in the changelog.",
]);

requireIncludes("docs/quality-gates.md", qualityDoc, [
  "`npm run verify:changelog`",
  "project-owned changelog structure, Unreleased section, Keep a Changelog and Conventional Commits references, and stale template-link bans",
  "does not generate release notes, run git-cliff, derive changes from Git history, create tags, publish releases, or rewrite commit history",
]);

requireIncludes("docs/site.md", siteDoc, [
  "M98 Changelog Metadata Gate Usage",
  "npm run verify:changelog",
  "project-owned changelog structure",
]);

if (failures.length > 0) {
  console.error("changelog metadata verification failed");
  for (const failure of failures) {
    console.error(`- ${failure}`);
  }
  process.exitCode = 1;
} else {
  console.log("changelog metadata verification passed");
}
